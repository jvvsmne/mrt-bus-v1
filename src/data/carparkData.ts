export function getCarparkOccupancyStatus(availableLots: number, totalLots: number): {
  status: 'Available' | 'Filling Fast' | 'Almost Full' | 'Full';
  percentage: number;
  badgeClass: string;
} {
  const percentage = Math.round(((totalLots - availableLots) / totalLots) * 100);
  const ratio = availableLots / totalLots;

  if (availableLots === 0) {
    return {
      status: 'Full',
      percentage: 100,
      badgeClass: 'bg-rose-100 text-rose-800 border-rose-200',
    };
  }
  if (ratio < 0.1 || availableLots < 25) {
    return {
      status: 'Almost Full',
      percentage,
      badgeClass: 'bg-amber-100 text-amber-800 border-amber-200',
    };
  }
  if (ratio < 0.35) {
    return {
      status: 'Filling Fast',
      percentage,
      badgeClass: 'bg-blue-100 text-blue-800 border-blue-200',
    };
  }
  return {
    status: 'Available',
    percentage,
    badgeClass: 'bg-emerald-100 text-emerald-800 border-emerald-200',
  };
}
